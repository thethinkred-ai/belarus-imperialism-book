"""Генератор промтов нового цикла рецензирования (review2/). Разовый запуск."""
import io, os

OUT = 'review2'
os.makedirs(OUT, exist_ok=True)

FOOT = '''

## Формат отчёта
По ядру (00-ядро.md): вердикт первой строкой; уровни (а) факты / (б) метод / (в) редактура;
чек-лист 8 провалов; приоритеты P0/P1/P2; предлагаемая формула для спорных выводов.
Не требуйте выводов сильнее статусов данных и не предлагайте возвращать ссылки на
источники из перечней РБ (прил. Г).'''

def make(fname, title, done, check, data, questions):
    b = f'# Промт рецензии: {title}\n\n(склейка: 00-ядро.md → этот файл → полный текст раздела)\n\n'
    b += f'## Раздел\n{title}\n\n'
    b += '## Что уже сделано в цикле v0.7–v0.7.1 (не считайте ошибкой сам факт — проверяйте КАЧЕСТВО)\n'
    for x in done: b += f'- {x}\n'
    b += '\n## Проверьте прежде всего\n'
    for x in check: b += f'- {x}\n'
    b += '\n## Данные для сверки (сбор 2026-10-08; проверяйте свежее по своим источникам)\n'
    for x in data: b += f'- {x}\n'
    b += '\n## Специфические вопросы\n'
    for q in questions: b += f'1. {q}\n' if isinstance(q, str) else ''
    b += FOOT
    io.open(os.path.join(OUT, fname), 'w', encoding='utf-8', newline='\n').write(b)
    print('ok', fname)

